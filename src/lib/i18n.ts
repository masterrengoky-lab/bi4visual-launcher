const DICTS: Record<Lang, Dict> = { ru, en, uk };

export const LANGS: { id: Lang; short: string; name: string }[] = [
  { id: "ru", short: "RU", name: "Русский" },
  { id: "en", short: "EN", name: "English" },
  { id: "uk", short: "UA", name: "Українська" },
];

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const d = DICTS[lang] ?? ru;
  return (key, vars) => {
    let s = d[key] ?? ru[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export const I18n = createContext<{ t: T; lang: Lang }>({ t: translator("ru"), lang: "ru" });

export function useT() {
  return useContext(I18n);
}

export function formatPlaytime(t: T, secs: number): string {
  if (secs < 60) return t("home.never");
  const h = Math.floor(secs / 3600);
  const m = Math.floor((secs % 3600) / 60);
  return h > 0 ? t("home.hours", { h, m }) : t("home.minutes", { m });
}
